"""Figures for Chapter 23. Numbers from code/ch23/output/ and from miniconnect.py itself."""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "common"))
from svgfig import Fig  # noqa: E402

HERE = Path(__file__).resolve().parents[1]
OUT = HERE / "output"
src = (HERE / "miniconnect.py").read_text().splitlines()
mark = lambda s: next(i for i, l in enumerate(src) if l.startswith(s))  # noqa: E731
n_session = mark("# ---- expressions") - mark("class SparkError")
n_df = len(src) - mark("# ---- expressions")
env = (OUT / "env.txt").read_text()
protos = sorted((HERE / "build" / "proto" / "spark" / "connect").glob("*.proto"))
n_msgs = sum(len(re.findall(r"^\s*message ", p.read_text(), re.M)) for p in protos)
ver = dict(re.findall(r"(grpcio|protobuf|pyarrow) ([\d.]+)", env))

# 1. The layers of a client
f = Fig(900, 390, "The layers of a Spark Connect client")
f.text(20, 26, f"miniconnect.py: {len(src)} lines of Python on three libraries (no pyspark)", 15, 700, anchor="start")
rows = [
    ("DataFrame API", f"{n_df} lines: Column, DataFrame, GroupedData, col, lit, fn", "Relation and Expression trees", "blue"),
    ("Session and RPCs", f"{n_session} lines: ExecutePlan, AnalyzePlan, ReattachExecute, ReleaseExecute, errors",
     "session ID, operation ID, error details", "purple"),
    ("Arrow", "pyarrow.ipc.open_stream on each ArrowBatch.data", f"pyarrow {ver['pyarrow']}", "ok"),
    ("protobuf", f"generated by protoc from {len(protos)} .proto files at v4.3.0: {n_msgs} message types",
     f"protobuf {ver['protobuf']}, grpcio-tools", "acc"),
    ("gRPC", "one channel, HTTP/2, the SparkConnectService stub", f"grpcio {ver['grpcio']}", "n"),
]
for i, (name, what, lib, kind) in enumerate(rows):
    y = 44 + i * 64
    f.rect(20, y, 860, 56, kind, r=8)
    f.text(36, y + 34, name, 16, 700, anchor="start", c=kind)
    f.text(220, y + 24, what, 12.5, 500, anchor="start", c=kind if kind != "n" else "fg")
    f.text(220, y + 43, lib, 11.5, 400, anchor="start", c="mute", mono=True)
f.text(20, 376, "The top two layers are the code of this chapter. The bottom three are libraries that exist in most languages.",
       11, 400, anchor="start", c="mute", italic=True)
f.save("ch23-layers")

# 2. The bytes of the smallest ExecutePlanRequest (step1_bytes.txt)
txt = (OUT / "step1_bytes.txt").read_text()
total = int(re.search(r"ExecutePlanRequest: (\d+) bytes", txt).group(1))
top = []
for line in txt.splitlines():
    m = re.match(r"  @([0-9a-f]{2}) .{9} (\S.*)$", line)
    if m and not m.group(2).startswith(" "):
        top.append((int(m.group(1), 16), m.group(2).split()[0]))
f = Fig(940, 300, "The bytes of an ExecutePlanRequest")
f.text(20, 26, f"ExecutePlanRequest for SELECT 1 AS x: {total} bytes (step1_bytes.txt)", 15, 700, anchor="start")
scale = 900 / total
kinds = {"session_id": "n", "user_context": "blue", "plan": "acc", "client_type": "purple"}
for j, (off, name) in enumerate(top):
    end = top[j + 1][0] if j + 1 < len(top) else total
    x, w = 20 + off * scale, (end - off) * scale
    f.rect(x, 44, w - 2, 54, kinds[name], r=5)
    f.text(x + w / 2, 66, name, min(12.5, w / 8), 700, c=kinds[name])
    f.text(x + w / 2, 86, f"{end - off} B, from 0x{off:02x}", 11, 400, c=kinds[name])
# the plan, opened
p0 = next(o for o, n in top if n == "plan")
x0 = 20 + p0 * scale
f.line(x0, 98, 120, 130, c="acc", dash=True)
f.line(x0 + 21 * scale, 98, 820, 130, c="acc", dash=True)
nest = [("1a 13", "plan: Plan, 19 bytes", "field 3, wire type 2 (length-delimited)"),
        ("0a 11", "root: Relation, 17 bytes", "field 1 of Plan"),
        ("52 0f", "sql: SQL, 15 bytes", "field 10 of Relation: 10 << 3 | 2 = 0x52"),
        ("0a 0d", "query = 'SELECT 1 AS x'", "field 1 of SQL, then 13 bytes of UTF-8")]
for i, (tag, name, why) in enumerate(nest):
    y = 134 + i * 38
    f.rect(120 + i * 24, y, 700 - i * 24, 32, "acc", r=5)
    f.text(132 + i * 24, y + 21, tag, 13, 700, anchor="start", c="acc", mono=True)
    f.text(200 + i * 24, y + 21, name, 13, 600, anchor="start", c="acc")
    f.text(808, y + 21, why, 11, 400, anchor="end", c="mute")
f.save("ch23-request-bytes")
